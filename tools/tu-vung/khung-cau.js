// Lien tu don le / khung mot ve — dung khi khong tim thay cap
const DON = ['要不是','尽管','虽然','因为','如果','要是','只要','只有','无论','不管','即使','除了','不然','否则','甚至','不是……而是','而不是','一边','越来越','根据','按照','总是','为了','例如','其中','一般情况下'];

const NOI_VE_SAU = ['却','但','而且','但是','可是','不过','而','所以','因此','还是','才'];
function tim(s) {
  s = String(s || '');
  for (const [a, b] of CAP) {
    const i = s.indexOf(a);
    if (i < 0) continue;
    const j = s.indexOf(b, i + a.length);
    if (j > i) return a + '……' + b + '……';
  }
  for (const w of DON) if (s.indexOf(w) >= 0) return w + '……';
  // Cau ghep chi co MOT lien tu o ve sau (却 / 而 / 但是…): van la cau ghep,
  // nhung chi tinh khi cau that su co hai ve — tuc la co dau phay.
  if (s.indexOf('，') > 0) {
    for (const w of NOI_VE_SAU) {
      const i = s.indexOf(w);
      if (i > s.indexOf('，')) return '……，' + w + '……';
    }
  }
  return '';
}
module.exports = { tim: tim, CAP: CAP };
